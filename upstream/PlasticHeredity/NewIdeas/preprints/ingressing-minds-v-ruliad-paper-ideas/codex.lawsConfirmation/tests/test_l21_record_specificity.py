def test_records_reciprocal_and_exact_no_mutation():
    parents = np.arange(2048, dtype=float).reshape(2, 4, 16, 16)/4000.
    native = np.linspace(-.5, .5, 256).reshape(16, 16); before = parents.copy()
    records, orders = p.make_records(parents, native, p.DISPOSABLE)
    for life in range(2):
        np.testing.assert_array_equal(records[life, 0], parents[life, 3])
        np.testing.assert_array_equal(records[life, 1], native)
        np.testing.assert_array_equal(records[life, 2], parents[1-life, 3])
        np.testing.assert_array_equal(records[life, 3].ravel(), parents[life, 3].ravel()[orders[life]])
        np.testing.assert_array_equal(np.sort(records[life, 3].ravel()), np.sort(parents[life, 3].ravel()))
        np.testing.assert_array_equal(records[life, 4], -parents[life, 3])
        np.testing.assert_array_equal(np.sort(orders[life]), np.arange(256))
        np.testing.assert_allclose(p.geometry(records)[life, 0, :3], p.geometry(records)[life, 3, :3], rtol=0, atol=1e-14)
    records[0, 2] += 1
    np.testing.assert_array_equal(parents, before)
    assert not np.shares_memory(records, parents) and not np.shares_memory(records, native)


